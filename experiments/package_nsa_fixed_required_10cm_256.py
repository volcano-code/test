#!/usr/bin/env python3
"""Package NSA-style physical-print models under a fixed-required gate.

Requirement:
  export a model only if its fixed-axis result satisfies
  IoU >= 0.975, single body, and watertight.

The source fixed-axis models are generated by build_nsa_style_12_10cm_256.py.
This script does not relabel them as free/fixed mixed results; it records that
the accepted model is the fixed candidate.
"""
from __future__ import annotations

import json
import shutil
from pathlib import Path

import numpy as np
import trimesh
from scipy.ndimage import binary_erosion, generate_binary_structure, label

ROOT = Path("/home/lin/xvxinyao/ShadowForge")
SRC = ROOT / "results/nsa_style_12_10cm_256"
OUT = ROOT / "results/nsa_style_fixed_required_10cm_256"
IOU_MIN = 0.975
SAVE_MIN = 0.40
SAVE_MAX = 0.85
EROSION_MIN = 0.15
S6 = generate_binary_structure(3, 1)


def mesh_and_voxel_qa(stl: Path, voxels: Path) -> dict:
    mesh = trimesh.load(str(stl), force="mesh")
    parts = mesh.split(only_watertight=False)
    volume = np.load(voxels).astype(bool)
    _, cc6 = label(volume, structure=S6)
    erosion = float(binary_erosion(volume, S6).sum() / max(int(volume.sum()), 1))
    return {
        "mesh_watertight_recheck": bool(mesh.is_watertight),
        "mesh_parts_recheck": int(len(parts)),
        "mesh_faces": int(len(mesh.faces)),
        "mesh_vertices": int(len(mesh.vertices)),
        "mesh_extents_mm_recheck": [round(float(x), 2) for x in mesh.extents],
        "voxel_components6_recheck": int(cc6),
        "erosion_survival_recheck": round(erosion, 4),
    }


def main() -> None:
    manifest = json.loads((SRC / "MANIFEST.json").read_text())
    if OUT.exists():
        shutil.rmtree(OUT)
    OUT.mkdir(parents=True, exist_ok=True)

    accepted = []
    rejected = []
    cases = []
    for case in manifest["cases"]:
        out_case = {k: case[k] for k in ("case_id", "nsa_panel", "setup", "caution")}
        out_case["models"] = []
        for model in case["models"]:
            ok = (
                float(model["iou"]) >= IOU_MIN
                and bool(model["single"])
                and bool(model["watertight"])
                and float(model["saving"]) >= SAVE_MIN
                and float(model["saving"]) <= SAVE_MAX
                and float(model["wall_mm_median_proxy"]) >= EROSION_MIN
            )
            record = {
                **model,
                "accepted_by_fixed_required_gate": bool(ok),
                "gate": {
                    "branch_required": "fixed",
                    "iou_min": IOU_MIN,
                    "single": True,
                    "watertight": True,
                    "saving_min": SAVE_MIN,
                    "saving_max": SAVE_MAX,
                    "erosion_survival_min": EROSION_MIN,
                },
                "selected_branch": "fixed",
                "selected_reason": "fixed_strict_gate_pass" if ok else "failed_fixed_required_gate",
            }
            if not ok:
                rejected.append(record)
                out_case["models"].append(record)
                continue

            src_stl = Path(model["stl"])
            src_npy = Path(model["voxels"])
            dst_dir = OUT / case["case_id"] / model["example"]
            dst_dir.mkdir(parents=True, exist_ok=True)
            dst_stl = dst_dir / f"{model['example']}_FIXED_10cm_256.stl"
            dst_npy = dst_dir / f"{model['example']}_FIXED_voxels256.npy"
            shutil.copy2(src_stl, dst_stl)
            shutil.copy2(src_npy, dst_npy)

            # Copy visual evidence if present.
            src_dir = src_stl.parent
            for sub in ("inputs", "silhouettes"):
                if (src_dir / sub).exists():
                    shutil.copytree(src_dir / sub, dst_dir / sub)
            record["stl"] = str(dst_stl)
            record["voxels"] = str(dst_npy)
            qa = mesh_and_voxel_qa(dst_stl, dst_npy)
            record["qa"] = qa
            qa_ok = (
                qa["mesh_watertight_recheck"]
                and qa["mesh_parts_recheck"] == 1
                and qa["voxel_components6_recheck"] == 1
                and qa["erosion_survival_recheck"] >= EROSION_MIN
                and max(qa["mesh_extents_mm_recheck"]) <= 100.01
            )
            record["qa_pass"] = bool(qa_ok)
            if not qa_ok:
                record["accepted_by_fixed_required_gate"] = False
                record["selected_reason"] = "failed_mesh_or_voxel_qa"
                rejected.append(record)
                out_case["models"].append(record)
                continue
            accepted.append(record)
            out_case["models"].append(record)
        cases.append(out_case)

    shutil.copy2(SRC / "INPUT_CONTACT_SHEET.png", OUT / "INPUT_CONTACT_SHEET.png")
    summary = {
        "schema": "nsa_style_fixed_required_10cm_256_v1",
        "source_manifest": str(SRC / "MANIFEST.json"),
        "branch_policy": "fixed-required strict gate: IoU>=0.975, single=true, watertight=true, saving in [0.40,0.85], erosion_survival>=0.15, mesh QA pass",
        "note": "These are fixed-axis TFS models, not free-branch exports.",
        "n_cases": len(cases),
        "n_models": len(accepted) + len(rejected),
        "n_accepted": len(accepted),
        "n_rejected": len(rejected),
        "cases": cases,
        "flat_examples": accepted + rejected,
    }
    (OUT / "MANIFEST.json").write_text(json.dumps(summary, indent=2, ensure_ascii=False))
    (OUT / "BATCH_MANIFEST.json").write_text(json.dumps(accepted + rejected, indent=2, ensure_ascii=False))
    print(f"DONE -> {OUT}")
    print(f"accepted={len(accepted)} rejected={len(rejected)}")
    for rec in accepted:
        print(f"{rec['example']}: fixed IoU={rec['iou']} saving={rec['saving']} stl={Path(rec['stl']).name}")


if __name__ == "__main__":
    main()
